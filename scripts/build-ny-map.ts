// New York State outline for the Home map (spec §6.1.7, plan §3). From the committed
// GeoJSON: keep the mainland and Long Island, project with an Albers equal-area conic
// (parallels 41° and 44.5°, centred −75.8°, 42.9°), fit to a 1000-wide viewBox with 20 of
// padding, simplify (Visvalingam) until the path is under 4 KB, round to integers, and
// write src/components/graphics/ny-map.generated.ts with the six places projected the same
// way. Run by `pnpm gen`; CI fails if the output drifts.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
type Pos = [number, number];

// Places (spec §6.1.7; O8: approximate until verified)
const PLACES = [
  { id: "catskill", label: "Catskill", lat: 42.217, lng: -73.865, kind: "taproom" },
  { id: "hudson-falls", label: "Hudson Falls", lat: 43.301, lng: -73.586, kind: "source" },
  { id: "cairo", label: "Cairo", lat: 42.299, lng: -73.998, kind: "source" },
  { id: "altamont", label: "Altamont", lat: 42.7, lng: -74.034, kind: "source" },
  { id: "hammondsport", label: "Hammondsport", lat: 42.408, lng: -77.224, kind: "source" },
  { id: "livingston", label: "Livingston", lat: 42.142, lng: -73.778, kind: "origin" },
] as const;

const rad = Math.PI / 180;
const [phi1, phi2, phi0, lam0] = [41 * rad, 44.5 * rad, 42.9 * rad, -75.8 * rad];
const n = (Math.sin(phi1) + Math.sin(phi2)) / 2;
const C = Math.cos(phi1) ** 2 + 2 * n * Math.sin(phi1);
const rho0 = Math.sqrt(C - 2 * n * Math.sin(phi0)) / n;
function albers([lng, lat]: Pos): Pos {
  const rho = Math.sqrt(C - 2 * n * Math.sin(lat * rad)) / n;
  const theta = n * (lng * rad - lam0);
  return [rho * Math.sin(theta), -(rho0 - rho * Math.cos(theta))]; // y down
}

const area = (r: Pos[]) =>
  Math.abs(
    r.reduce((s, [x, y], i) => {
      const [x2, y2] = r[(i + 1) % r.length] as Pos;
      return s + x * y2 - x2 * y;
    }, 0),
  ) / 2;

export async function buildNyMap(): Promise<void> {
  const geo = JSON.parse(readFileSync(join(root, "scripts/data/ny-state.geo.json"), "utf8")) as {
    geometry: { coordinates: Pos[][][] };
  };
  // outer rings only, projected, biggest first; keep the mainland and Long Island
  const rings = geo.geometry.coordinates
    .map((poly) => (poly[0] ?? []).map(albers))
    .sort((a, b) => area(b) - area(a))
    .slice(0, 2);

  // fit
  const all = rings.flat();
  const xs = all.map((p) => p[0]);
  const ys = all.map((p) => p[1]);
  const [minX, maxX, minY, maxY] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)];
  const W = 1000;
  const PAD = 20;
  const k = (W - 2 * PAD) / (maxX - minX);
  const H = Math.round((maxY - minY) * k + 2 * PAD);
  const fit = ([x, y]: Pos): Pos => [(x - minX) * k + PAD, (y - minY) * k + PAD];

  // Visvalingam–Whyatt: drop the point making the smallest triangle until under the budget
  function simplify(r: Pos[], keep: number): Pos[] {
    const pts = [...r];
    const tri = (a: Pos, b: Pos, c: Pos) =>
      Math.abs((b[0] - a[0]) * (c[1] - a[1]) - (c[0] - a[0]) * (b[1] - a[1])) / 2;
    while (pts.length > keep) {
      let min = Infinity;
      let at = -1;
      for (let i = 0; i < pts.length; i++) {
        const a = pts[(i - 1 + pts.length) % pts.length] as Pos;
        const c = pts[(i + 1) % pts.length] as Pos;
        const t = tri(a, pts[i] as Pos, c);
        if (t < min) {
          min = t;
          at = i;
        }
      }
      pts.splice(at, 1);
    }
    return pts;
  }

  function toPath(rs: Pos[][]): string {
    return rs
      .map((r) => {
        const pts = r
          .map(([x, y]) => [Math.round(x), Math.round(y)] as Pos)
          .filter((p, i, arr) => {
            const prev = arr[i - 1];
            return !prev || prev[0] !== p[0] || prev[1] !== p[1];
          });
        let d = `M${pts[0]?.[0]} ${pts[0]?.[1]}`;
        for (let i = 1; i < pts.length; i++) {
          const [x, y] = pts[i] as Pos;
          const [px, py] = pts[i - 1] as Pos;
          d += `l${x - px} ${y - py}`;
        }
        return `${d}z`;
      })
      .join("");
  }

  const fitted = rings.map((r) => r.map(fit));
  let budget = 420;
  let path = "";
  do {
    const [main, li] = fitted as [Pos[], Pos[]];
    path = toPath([simplify(main, budget), simplify(li, Math.max(12, Math.round(budget / 12)))]);
    budget -= 10;
  } while (path.length >= 4000 && budget > 40);

  const places = PLACES.map((p) => {
    const [x, y] = fit(albers([p.lng, p.lat]));
    return { id: p.id, label: p.label, kind: p.kind, x: Math.round(x), y: Math.round(y) };
  });

  const out = [
    "// Generated by scripts/build-ny-map.ts from scripts/data/ny-state.geo.json. Do not edit.",
    `export const NY_VIEWBOX = "0 0 ${W} ${H}";`,
    `export const NY_PATH = ${JSON.stringify(path)};`,
    `export const NY_PLACES = ${JSON.stringify(places)} as const;`,
    "",
  ].join("\n");
  writeFileSync(join(root, "src/components/graphics/ny-map.generated.ts"), out);
  console.log(`ny-map: ${path.length} bytes, viewBox 0 0 ${W} ${H}`);
}

// run directly (node scripts/build-ny-map.ts) as well as from gen.ts
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await buildNyMap();
