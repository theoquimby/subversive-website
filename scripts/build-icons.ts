// Icon sprite (spec §3.9, plan M1 item 10): src/components/graphics/icons/*.svg →
// public/brand/icons.svg (one <symbol> each) and icons.generated.ts (the typed name list).
// SVGO keeps the viewBox. Run through `pnpm gen`; CI fails if the output drifts.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { optimize } from "svgo";
import svgoConfig from "../svgo.config.ts";

const root = fileURLToPath(new URL("..", import.meta.url));
const dir = join(root, "src/components/graphics/icons");

export async function buildIcons(): Promise<void> {
  const names = readdirSync(dir)
    .filter((f) => f.endsWith(".svg"))
    .map((f) => f.replace(/\.svg$/, ""))
    .sort();

  const symbols = names.map((name) => {
    const src = readFileSync(join(dir, `${name}.svg`), "utf8");
    const { data } = optimize(src, { path: `${name}.svg`, ...svgoConfig });
    const inner = data.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
    return `  <symbol id="icon-${name}" viewBox="0 0 24 24">${inner}</symbol>`;
  });

  const sprite = [
    '<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="2" stroke-linejoin="miter" stroke-linecap="square">',
    "  <!-- Generated by scripts/build-icons.ts from src/components/graphics/icons. Do not edit. -->",
    ...symbols,
    "</svg>",
    "",
  ].join("\n");
  writeFileSync(join(root, "public/brand/icons.svg"), sprite);

  const ts = [
    "// Generated by scripts/build-icons.ts. Do not edit.",
    `export const ICON_NAMES = ${JSON.stringify(names)} as const;`,
    "export type IconName = (typeof ICON_NAMES)[number];",
    "",
  ].join("\n");
  writeFileSync(join(root, "src/components/graphics/icons.generated.ts"), ts);
  console.log(`icons: ${names.length} symbols`);
}
